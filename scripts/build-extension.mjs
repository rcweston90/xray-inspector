import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const corePath = resolve(root, 'src/xray.mjs');
const outputPath = resolve(root, 'extension/content.js');
const core = await readFile(corePath, 'utf8');
const expectedExports = ['measureElement', 'createEvidence', 'downloadEvidence', 'mountXRay'];

for (const name of expectedExports) {
  if (!core.includes(`export function ${name}`)) {
    throw new Error(`Portable core no longer exports ${name}; review the extension adapter before rebuilding.`);
  }
}

const classicCore = core.replaceAll('export function ', 'function ');
const generated = `// Generated by scripts/build-extension.mjs from ../src/xray.mjs.\n` +
  `// Do not edit this file directly.\n` +
  `(() => {\n${classicCore}\n` +
  `const stateKey = Symbol.for('xray-inspector.extension.cleanup');\n` +
  `const activeCleanup = globalThis[stateKey];\n` +
  `if (typeof activeCleanup === 'function') {\n` +
  `  activeCleanup();\n` +
  `  return 'closed';\n` +
  `}\n` +
  `let cleanup;\n` +
  `cleanup = mountXRay({ onClose() {\n` +
  `  if (globalThis[stateKey] === cleanup) delete globalThis[stateKey];\n` +
  `} });\n` +
  `globalThis[stateKey] = cleanup;\n` +
  `return 'opened';\n` +
  `})();\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
